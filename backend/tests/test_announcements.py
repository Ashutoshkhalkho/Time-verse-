async def get_token_for(client: AsyncClient, email: str) -> str:
    response = await client.post(
        "/api/v1/auth/login",
        json={"email": email, "password": DEFAULT_DEMO_PASSWORD},
    )
    assert response.status_code == 200
    return response.json()["tokens"]["access_token"]


@pytest.mark.asyncio
async def test_announcements_lifecycle_and_rbac(client: AsyncClient):
    """Verifies administrator announcement management, role-based visibility, and broadcast integration."""
    admin_token = await get_token_for(client, "admin@timewise.edu")
    student_token = await get_token_for(client, "student.aarav@timewise.edu")
    faculty_token = await get_token_for(client, "teacher.sharma@timewise.edu")

    # 1. Admin creates announcement
    create_resp = await client.post(
        "/api/v1/announcements",
        headers={"Authorization": f"Bearer {admin_token}"},
        json={
            "title": "Semester Registration Deadline Extended",
            "content": "Course registration for odd semester has been extended until Friday 5:00 PM.",
            "category": "ACADEMIC_NOTICE",
            "severity": "INFORMATIONAL",
            "target_audience": "STUDENTS",
            "department_id": "dept_cs",
            "is_pinned": True,
            "broadcast_as_alert": True,
        },
    )
    assert create_resp.status_code == 201
    ann = create_resp.json()
    ann_id = ann["id"]
    assert ann["is_pinned"] is True

    # 2. Student list shows this announcement
    student_list = await client.get(
        "/api/v1/announcements",
        headers={"Authorization": f"Bearer {student_token}"},
    )
    assert student_list.status_code == 200
    titles = [a["title"] for a in student_list.json()]
    assert "Semester Registration Deadline Extended" in titles

    # 3. Student has corresponding Alert generated by broadcast
    alerts_resp = await client.get(
        "/api/v1/alerts",
        headers={"Authorization": f"Bearer {student_token}"},
    )
    assert alerts_resp.status_code == 200
    alert_titles = [al["title"] for al in alerts_resp.json()["alerts"]]
    assert "Semester Registration Deadline Extended" in alert_titles

    # 4. Student cannot create announcement (403 Forbidden)
    student_create = await client.post(
        "/api/v1/announcements",
        headers={"Authorization": f"Bearer {student_token}"},
        json={
            "title": "Unauthorized Notice",
            "content": "This should be rejected.",
            "category": "ACADEMIC_NOTICE",
        },
    )
    assert student_create.status_code == 403

    # 5. Admin updates announcement
    update_resp = await client.put(
        f"/api/v1/announcements/{ann_id}",
        headers={"Authorization": f"Bearer {admin_token}"},
        json={"title": "Updated: Semester Registration Deadline Extended"},
    )
    assert update_resp.status_code == 200
    assert update_resp.json()["title"] == "Updated: Semester Registration Deadline Extended"

    # 6. Admin deletes announcement
    delete_resp = await client.delete(
        f"/api/v1/announcements/{ann_id}",
        headers={"Authorization": f"Bearer {admin_token}"},
    )
    assert delete_resp.status_code == 200
