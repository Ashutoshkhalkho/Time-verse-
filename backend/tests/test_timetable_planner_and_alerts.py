# SCENARIO 10: Duplicate notifications avoided and delivery failure/retry works
# ==============================================================================
@pytest.mark.asyncio
async def test_scenario_10_alert_deduplication_and_retry(client: AsyncClient):
    hod_token = await get_token_for(client, "hod.cs@timewise.edu")
    headers = {"Authorization": f"Bearer {hod_token}"}

    # Dispatch emergency alert
    em_res = await client.post(
        "/api/v1/alerts/trigger-workflow-event",
        headers=headers,
        json={
            "category": "EMERGENCY",
            "title": "Severe Rain Alert: Lab Sessions Suspended",
            "message": "Due to weather, all afternoon labs for CS-3A are suspended.",
            "cohort_section_id": "sec_cs_3a",
        },
    )
    assert em_res.status_code == 201

    # Fetch alerts
    alerts_res = await client.get(
        "/api/v1/alerts?category=EMERGENCY",
        headers=headers,
    )
    assert alerts_res.status_code == 200
    alert_list = alerts_res.json()["alerts"]
    assert len(alert_list) > 0
    target_alert = alert_list[0]

    # Test delivery retry
    retry_res = await client.post(
        f"/api/v1/alerts/{target_alert['id']}/retry",
        headers=headers,
    )
    assert retry_res.status_code == 200
    assert retry_res.json()["delivery_channels"]["email"]["status"] == "DELIVERED"

    # Test resolution update: PENDING -> UNDER_REVIEW -> RESOLVED
    res_update = await client.patch(
        f"/api/v1/alerts/{target_alert['id']}/resolution",
        headers=headers,
        json={"status": "UNDER_REVIEW", "notes": "HOD investigating rescheduled lab slot"},
    )
    assert res_update.status_code == 200
    assert res_update.json()["resolution_status"] == "UNDER_REVIEW"

    # Resolve alert
    resolve_update = await client.patch(
        f"/api/v1/alerts/{target_alert['id']}/resolution",
        headers=headers,
        json={"status": "RESOLVED", "notes": "Labs rescheduled to next Tuesday"},
    )
    assert resolve_update.status_code == 200
    assert resolve_update.json()["resolution_status"] == "RESOLVED"


