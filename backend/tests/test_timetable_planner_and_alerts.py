# SCENARIO 2: Hard-constraint conflict detected and CANNOT be published as valid
# ==============================================================================
@pytest.mark.asyncio
async def test_scenario_2_conflict_prevents_publishing(client: AsyncClient):
    hod_token = await get_token_for(client, "hod.cs@timewise.edu")
    headers = {"Authorization": f"Bearer {hod_token}"}

    # Inject clash into master test timetable
    clash_res = await client.post(
        "/api/v1/conflicts/inject-demo-clash?timetable_id=tt_dept_cs_master_v1",
        headers=headers,
    )
    assert clash_res.status_code == 200
    tt_id = clash_res.json()["timetable_id"]

    # Verify conflict detector flags it
    check_res = await client.get(
        f"/api/v1/conflicts?timetable_id={tt_id}",
        headers=headers,
    )
    assert check_res.status_code == 200
    assert check_res.json()["is_conflict_free"] is False
    assert check_res.json()["critical_conflicts_count"] > 0

    # Attempt to publish invalid timetable -> Must be rejected with 422 / ValidationException
    pub_attempt = await client.post(
        f"/api/v1/timetables/{tt_id}/publish",
        headers=headers,
    )
    assert pub_attempt.status_code == 422
    assert "hard constraint violations detected" in pub_attempt.json()["detail"].lower()

    # Restore clash-free state for subsequent tests
    await client.post(
        f"/api/v1/conflicts/restore-conflict-free?timetable_id={tt_id}",
        headers=headers,
    )


