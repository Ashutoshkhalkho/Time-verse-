# SCENARIO 1: HOD generates, edits, validates, and publishes a valid timetable
# ==============================================================================
@pytest.mark.asyncio
async def test_scenario_1_hod_workflow(client: AsyncClient):
    hod_token = await get_token_for(client, "hod.cs@timewise.edu")
    headers = {"Authorization": f"Bearer {hod_token}"}

    # 1. HOD generates timetable via CP-SAT
    gen_res = await client.post(
        "/api/v1/timetables/generate",
        headers=headers,
        json={
            "department_id": "dept_cs",
            "academic_term_id": "term_odd_2026",
            "time_limit_seconds": 5,
            "notes": "Generated by HOD test",
        },
    )
    assert gen_res.status_code == 200
    gen_data = gen_res.json()
    assert gen_data["is_valid"] is True
    new_tt_id = gen_data["timetable_id"]
    assert new_tt_id != ""

    # 2. HOD edits: adds a new valid session
    add_res = await client.post(
        f"/api/v1/timetables/{new_tt_id}/sessions",
        headers=headers,
        json={
            "subject_id": "sub_cs303",
            "teacher_id": "tch_patel",
            "room_id": "rm_lh102",
            "cohort_section_id": "sec_cs_3a",
            "time_slot_id": "ts_d5_p6",
        },
    )
    assert add_res.status_code == 201

    # 3. HOD validates conflicts
    val_res = await client.get(
        f"/api/v1/conflicts?timetable_id={new_tt_id}",
        headers=headers,
    )
    assert val_res.status_code == 200
    val_data = val_res.json()
    assert val_data["is_conflict_free"] is True

    # 4. HOD publishes timetable
    pub_res = await client.post(
        f"/api/v1/timetables/{new_tt_id}/publish",
        headers=headers,
    )
    assert pub_res.status_code == 200
    pub_data = pub_res.json()
    assert pub_data["status"] == "PUBLISHED"


